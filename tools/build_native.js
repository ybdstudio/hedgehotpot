#!/usr/bin/env node
/* Build the TikTok Mini Games native package from the shared web source.
   usage: node tools/build_native.js [outDir=dist] [--appid ID] [--rewarded AD_ID] [--interstitial AD_ID] [--zip]
   out:   <outDir>/hedgehotpot/ (native code)   <outDir>/emulator/index.html (desktop test only)
   --release checks real configuration + the supplied checker; --zip uses the official TikTok packer. */
const fs = require('fs'), path = require('path'), cp = require('child_process');
const R = path.join(__dirname, '..'), argv = process.argv.slice(2);
const opt = k => { const i = argv.indexOf('--' + k); return i >= 0 ? argv[i + 1] : null; };
const outDir = path.resolve(argv[0] && !argv[0].startsWith('--') ? argv[0] : path.join(R, 'dist'));
const rd = p => fs.readFileSync(path.join(R, p), 'utf8');
const distRoot = path.resolve(R, 'dist');
if (outDir !== distRoot && !outDir.startsWith(distRoot + path.sep)) throw new Error('Build output must be inside this repo/dist; refusing recursive cleanup elsewhere.');
const PKG = path.join(outDir, 'hedgehotpot');
const SHARED = ['config', 'nav', 'conveyor', 'game', 'bot', 'assets', 'render', 'audio'].map(n => 'js/' + n + '.js');
const NATIVE = ['ui_native', 'hs_native', 'ads_native', 'minis_native', 'main_native'].map(n => 'native/src/' + n + '.js');

// ---- HS SDK config (native/hs-config.json + defaults from native/hedgehotpot.hs-dashboard.json)
const HS_FILE = fs.existsSync(path.join(R, 'native/hs-config.json')) ? 'native/hs-config.json' : (console.warn('! native/hs-config.json missing: using empty draft credentials from native/hs-config.example.json (ads/cloud off)'), 'native/hs-config.example.json');
const HS = JSON.parse(rd(HS_FILE)), DASH = JSON.parse(rd('native/hedgehotpot.hs-dashboard.json'));
if (opt('hs-key')) HS.sdkKey = opt('hs-key'); if (opt('hs-game')) HS.gameId = opt('hs-game');
const hsConfig = () => 'window.CST.HS_CONFIG = ' + JSON.stringify({ gameId: HS.gameId, sdkKey: HS.sdkKey, places: HS.places, pacing: HS.pacing,
  defaults: { rewards: DASH.iaa_config.rewards, items: DASH.iaa_config.items } }) + ';\n';
{ const labels = new Set(DASH.iaa_config.placements.map(p => p.label));
  for (const l of Object.values(HS.places)) if (!labels.has(l)) throw new Error(`place "${l}" missing from the dashboard JSON`); }

// ---- game.js
const manifest = rd('js/manifest.js').split('"file":"assets/').join('"file":"res/assets/');   // atlases live in subpackage 'res'
const sec = (name, body) => `/* ---- ${name} ---- */\n` + body + '\n';
let js = '/* Hedge Hotpot Conveyor — TikTok Mini Games native build (generated by tools/build_native.js) */\n\n'
  + sec('native/src/adapter.js', rd('native/src/adapter.js') + manifest + '\n' + rd('native/src/uiart_files.js'))
  + SHARED.concat(NATIVE).map(f => sec(f, (f.endsWith('hs_native.js') ? hsConfig() : '') + rd(f))).join('');
const ids = { REWARDED_AD_UNIT_ID: opt('rewarded'), INTERSTITIAL_AD_UNIT_ID: opt('interstitial') };
for (const k in ids) if (ids[k]) js = js.split(`'${k}'`).join(`'${ids[k]}'`);
new Function(js);   // syntax check

// ---- package
fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(path.join(PKG, 'ui'), { recursive: true }); fs.mkdirSync(path.join(PKG, 'res/assets'), { recursive: true });
fs.writeFileSync(path.join(PKG, 'game.js'), js);
fs.copyFileSync(path.join(R, 'native/project/game.json'), path.join(PKG, 'game.json'));
const cfg = JSON.parse(rd('native/project/project.config.json')); if (opt('appid')) cfg.appid = opt('appid');
fs.writeFileSync(path.join(PKG, 'project.config.json'), JSON.stringify(cfg, null, 2));
fs.copyFileSync(path.join(R, 'native/project/res_game.js'), path.join(PKG, 'res/game.js'));
const uiFiles = JSON.parse(rd('native/src/uiart_files.js').replace(/^[^{]*/, '').replace(/;\s*$/, ''));
for (const f of Object.values(uiFiles)) { const b = path.basename(f), src = [path.join(R, 'native/project/ui', b), path.join(R, 'assets/ui', b)].find(fs.existsSync);
  if (!src) throw new Error('missing UI art ' + b); fs.copyFileSync(src, path.join(PKG, f)); }
for (const f of fs.readdirSync(path.join(R, 'assets'))) if (f.endsWith('.webp')) fs.copyFileSync(path.join(R, 'assets', f), path.join(PKG, 'res/assets', f));
for (const f of ['hs-game.js', 'hs-sdk.min.js']) fs.copyFileSync(path.join(R, 'native/hs-sdk', f), path.join(PKG, f));
fs.copyFileSync(path.join(R, 'native/hedgehotpot.hs-dashboard.json'), path.join(outDir, 'hedgehotpot.hs-dashboard.json'));   // next to the package (hs-check), not uploaded
fs.mkdirSync(path.join(outDir, 'emulator')); fs.copyFileSync(path.join(R, 'native/emulator.html'), path.join(outDir, 'emulator/index.html'));

// ---- size check (TikTok: main package 4 MB, total 30 MB)
const du = d => fs.readdirSync(d, { withFileTypes: true }).reduce((s, e) => s + (e.isDirectory() ? du(path.join(d, e.name)) : fs.statSync(path.join(d, e.name)).size), 0);
const tot = du(PKG), sub = du(path.join(PKG, 'res')), MB = b => (b / 1048576).toFixed(2);
console.log(`built ${PKG}\n  main ${MB(tot - sub)} MB / 4   total ${MB(tot)} MB / 30   appid=${cfg.appid}`);
if (tot - sub > 4 * 1048576 || tot > 30 * 1048576) { console.error('SIZE LIMIT EXCEEDED'); process.exit(1); }
if (!/^\d+$/.test(cfg.appid || '')) console.log('DRAFT ONLY: App ID not configured; TikTok upload is blocked until supplied.');
const missing = [];
if (!/^\d+$/.test(cfg.appid || '')) missing.push('TikTok App ID');
if (!/^\d+$/.test(HS.gameId || '')) missing.push('HS Game ID');
if (!HS.sdkKey) missing.push('HS SDK key');
if (DASH.iaa_config.placements.some(p => p.ads.some(a => !/^ad[a-zA-Z0-9]+$/.test(a.id)))) missing.push('ad unit IDs');
if (argv.includes('--release') && missing.length) throw new Error('Release blocked: missing ' + missing.join(', '));
if (argv.includes('--release') && cfg.appid !== HS.gameId) throw new Error('Release blocked: HS Game ID must match the registered TikTok App ID.');
if (argv.includes('--release')) cp.execFileSync(process.execPath, [path.join(R,'vendor/hs-sdk-1.1.3/hs-check.mjs'),PKG], { stdio:'inherit' });
if (argv.includes('--zip')) cp.execFileSync(process.execPath, [path.join(R,'vendor/hs-sdk-1.1.3/web/hs-web.mjs'),'pack',PKG,'--tiktok'], { stdio:'inherit' });
