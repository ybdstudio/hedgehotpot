"""Inline the UI art (assets/ui/*.webp) as data URIs into js/uiart.js so the game stays one self-contained file."""
import base64, os, json
G=os.path.join(os.path.dirname(__file__),'..'); D=f'{G}/assets/ui'
m={f[:-5]:'data:image/webp;base64,'+base64.b64encode(open(f'{D}/{f}','rb').read()).decode() for f in sorted(os.listdir(D)) if f.endswith('.webp')}
open(f'{G}/js/uiart.js','w').write('/* generated by tools/build_uiart.py */\nwindow.CST=window.CST||{};CST.UIART='+json.dumps(m)+';\n')
print(len(m),'images', round(sum(len(v) for v in m.values())/1e3),'kB')
